//============================================================
// HUDIds.cs
// - HUD 내부 동작 제어 전용 (프리팹 식별 X)
// - Mode: 상태 전환 정책 (어떤 섹션을 켤지 결정)
// - Section: 실제 켜고/끄는 기능 단위(Flags 조합)
//============================================================
using System;

public static class HUDIds
{
    // ---------------------------------------------------------
    // HUD Mode
    // ---------------------------------------------------------
    public enum Mode
    {
        None = 0,

        Explore = 10,   // 탐험
        Combat = 20,    // 일반 전투
        Boss = 30,      // 보스전
        Cutscene = 40,  // 컷씬
        Spectate = 50,  // 관전
    }

    // ---------------------------------------------------------
    // HUD Section (조합 가능)
    // ---------------------------------------------------------
    [Flags]
    public enum Section
    {
        None = 0,

        TopBar        = 1 << 0,
        CombatPanel   = 1 << 1,
        ExplorePanel  = 1 << 2,
        BossPanel     = 1 << 3,
        SystemNotices = 1 << 4,
    }
}
