//============================================================
// HUDIds.cs
// - HUD 내부 동작 제어 전용 (프리팹 식별 X)
// - Mode: 상태 전환 정책 (어떤 섹션을 켤지 결정)
// - Section: 실제 켜고/끄는 기능 단위(Flags 조합)
//============================================================
using System;

public static class HUDIds
{
    // ---------------------------------------------------------
    // HUD Mode
    // ---------------------------------------------------------
    public enum Mode
    {
        None = 0,

        Lobby  = 10,    // 로비
        Combat = 20,    // 일반 전투
        Boss = 30,      // 보스전
        Cutscene = 40,  // 컷씬
        BossCutscene = 45,  // 보스 페이즈 전환 컷신 — 보스 HP바만 남긴다(바가 차오르는 걸 보여 준다)
        // 50 관전 · 60 퍼즐은 켜는 곳이 없어 걷었다(09-28 HUD 레거시 정리) — 번호는 다시 쓰지 않는다.
    }

    // ---------------------------------------------------------
    // HUD Section (조합 가능)
    // ---------------------------------------------------------
    [Flags]
    public enum Section
    {
        None = 0,

        TopBar          = 1 << 0,
        CombatPanel     = 1 << 1,
        BossPanel       = 1 << 3,
        Minimap         = 1 << 5,
        CovenantPanel   = 1 << 6,
        // 1<<2 GridPanel · 1<<4 SystemNotices는 배선된 판이 없어(0) 켜도 아무 일이 없었다 — 걷음(09-28).
        // 시스템 알림은 CombatPanelView.ShowBuffNotice 한 칸이 맡는다.
    }
}
